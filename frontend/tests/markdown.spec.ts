import { test, expect } from '@playwright/test'

const api = 'http://127.0.0.1:19518/api'
const source = '# 风雪夜\n\n**故人**与*来客*重逢。\n\n> 留下线索\n\n- [x] 开始\n- [ ] 出发\n\n| 人物 | 状态 |\n| --- | --- |\n| 沈舟 | 等待 |\n\n```js\nconst clue = 1\n```\n\n~~旧线索~~\n\n[危险链接](javascript:alert(1))\n\n<script>window.mdInjected = true</script>'

test('原文与 Markdown 覆盖正文大纲梗概历史，切换及复制不改变源文', async ({ page, context, request }, testInfo) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const book = await (await request.post(`${api}/books`, { data: { title: 'Markdown 验收', description: '**书籍简介**' } })).json()
  const chapter = await (await request.post(`${api}/books/${book.id}/chapters`, { data: { title: '初见', content: source } })).json()
  try {
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`/books/${book.id}/reader`)
    await expect(page.getByLabel('正文内容', { exact: true })).toHaveText(source)
    await page.getByRole('button', { name: 'Markdown', exact: true }).click()
    const body = page.getByLabel('正文内容', { exact: true })
    await expect(body.getByRole('heading', { name: '风雪夜', exact: true })).toBeVisible()
    await expect(body.locator('strong')).toHaveText('故人')
    await expect(body.getByRole('table')).toBeVisible()
    await expect(body.getByRole('checkbox')).toHaveCount(2)
    await expect(body.locator('pre code')).toHaveText('const clue = 1\n')
    expect(await body.getByRole('link', { name: '危险链接' }).getAttribute('href')).not.toContain('javascript:')
    expect(await page.evaluate(() => 'mdInjected' in window)).toBe(false)
    await page.getByRole('button', { name: '复制正文内容', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe(source)
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    const editor = page.getByRole('textbox', { name: '章节正文', exact: true })
    const draft = source + '\n\n## 新线索\n\n还未保存。'
    await editor.fill(draft)
    await expect(page.getByLabel('章节正文预览', { exact: true }).getByRole('heading', { name: '新线索' })).toBeVisible()
    await page.getByRole('button', { name: '原始', exact: true }).click()
    await expect(editor).toHaveValue(draft)
    await expect(page.getByLabel('章节正文预览', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '复制章节正文', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe(draft)
    await page.getByRole('button', { name: '保存新版本', exact: true }).click()
    await expect(page.getByText('有未保存修改')).toHaveCount(0)
    expect((await (await request.get(`${api}/chapters/${chapter.id}`)).json()).current_content).toBe(draft)
    await page.getByRole('button', { name: '查看 v1', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Markdown', exact: true }).click()
    await expect(page.getByLabel('历史正文全文', { exact: true }).getByRole('table')).toBeVisible()
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click()
    await page.getByRole('button', { name: '大纲', exact: true }).click()
    await page.getByRole('textbox', { name: '大纲全文', exact: true }).fill(source)
    await expect(page.getByLabel('大纲全文预览', { exact: true }).getByRole('table')).toBeVisible()
    await page.getByRole('button', { name: '保存大纲', exact: true }).click()
    await page.getByRole('button', { name: '查看 v1', exact: true }).click()
    await expect(page.getByLabel('历史大纲全文', { exact: true }).getByRole('heading', { name: '风雪夜' })).toBeVisible()
    await page.getByRole('button', { name: '复制历史大纲全文' }).click()
    await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe(source)
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click()
    await page.reload()
    await expect(page.getByRole('button', { name: 'Markdown', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: '正文', exact: true }).click()
    await page.route(`**/chapters/${chapter.id}/summary`, route => route.fulfill({ json: { chapter_id: chapter.id, status: 'completed', message: '已生成', chapter: { ...chapter, current_content: draft, summary: '## 本章概述\n\n**再次重逢**', summary_is_stale: false } } }))
    await page.getByRole('button', { name: '生成本章梗概', exact: true }).click()
    await expect(page.getByLabel('本章梗概内容', { exact: true }).getByRole('heading', { name: '本章概述' })).toBeVisible()
    await page.getByRole('button', { name: '阅读', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('markdown-reader.png'), fullPage: true })
    await page.setViewportSize({ width: 900, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '原始', exact: true }).click()
    await expect(page.getByLabel('正文内容', { exact: true })).toHaveText(draft)
  } finally { await request.delete(`${api}/books/${book.id}`) }
})

test('每个输入框有 SVG 复制按钮，拒绝剪贴板访问时给出反馈', async ({ page, context, request }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const book = await (await request.post(`${api}/books`, { data: { title: '复制验收' } })).json()
  try {
    await page.goto(`/books/${book.id}/settings`)
    for (const input of await page.locator('input:not([type="checkbox"]):not([type="file"])').all()) {
      const holder = input.locator('..')
      await expect(holder.getByRole('button', { name: /^复制/ }).locator('svg')).toHaveCount(1)
    }
    await page.getByLabel('API Key', { exact: true }).fill('test-visible-buffer')
    await page.getByRole('button', { name: '复制API Key', exact: true }).click()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('test-visible-buffer')
    await page.getByLabel('Base URL', { exact: true }).fill('https://example.invalid/v1')
    await page.getByRole('button', { name: '复制Base URL' }).click()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('https://example.invalid/v1')
    await page.evaluate(() => { Object.defineProperty(navigator.clipboard, 'writeText', { configurable: true, value: () => Promise.reject(new Error('denied')) }) })
    await page.getByRole('button', { name: '复制Base URL' }).click()
    await expect(page.getByRole('button', { name: '复制Base URL' }).getByRole('status')).toHaveText('复制失败，请手动选择文本复制')
    await expect(page.getByLabel('Base URL', { exact: true })).toHaveValue('https://example.invalid/v1')
  } finally { await request.delete(`${api}/books/${book.id}`) }
})

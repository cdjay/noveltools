import { test, expect } from '@playwright/test'

const api = 'http://127.0.0.1:19518/api'

test('只保留三个工作入口，大纲全文可保存、查看历史与恢复', async ({ page, request }, testInfo) => {
  const book = await (await request.post(`${api}/books`, { data: { title: '全文大纲验收' } })).json()
  try {
    await page.goto(`/books/${book.id}/outline`)
    const navigation = page.locator('aside[aria-label="工作区导航"] nav')
    await expect(navigation.getByRole('button')).toHaveCount(3)
    for (const name of ['正文', '大纲', 'LLM 配置']) await expect(navigation.getByRole('button', { name, exact: true })).toBeVisible()
    const editor = page.getByRole('textbox', { name: '大纲全文', exact: true })
    await editor.fill('第一稿：风雪中启程。\n\n自由编写，不分段块。')
    await page.getByRole('button', { name: '保存大纲', exact: true }).click()
    await expect(page.getByText('当前 v1', { exact: true })).toBeVisible()
    await editor.fill('第二稿：在城门前遇见故人。')
    await page.getByRole('button', { name: '保存大纲', exact: true }).click()
    await expect(page.getByText('当前 v2', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '查看 v1', exact: true }).click()
    await expect(page.getByLabel('历史大纲全文')).toHaveText('第一稿：风雪中启程。\n\n自由编写，不分段块。')
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click()
    await page.getByRole('button', { name: '恢复 v1', exact: true }).click()
    await page.getByRole('button', { name: '恢复为新版本', exact: true }).click()
    await expect(page.getByText('当前 v3', { exact: true })).toBeVisible()
    await expect(editor).toHaveValue('第一稿：风雪中启程。\n\n自由编写，不分段块。')
    await page.reload()
    await expect(editor).toHaveValue('第一稿：风雪中启程。\n\n自由编写，不分段块。')
    await page.screenshot({ path: testInfo.outputPath('outline.png'), fullPage: true })
    await page.setViewportSize({ width: 900, height: 900 })
    await expect(editor).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await editor.fill('尚未保存的新稿')
    page.once('dialog', dialog => dialog.dismiss())
    await navigation.getByRole('button', { name: '正文', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/books/${book.id}/outline$`))
    await expect(editor).toHaveValue('尚未保存的新稿')
    // A rejected save leaves the draft available, including after a stale-version conflict.
    await page.route(`**/books/${book.id}/outline/versions`, route => route.request().method() === 'POST'
      ? route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ detail: '大纲已在其他窗口更新' }) })
      : route.continue())
    await page.getByRole('button', { name: '保存大纲', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('大纲已在其他窗口更新')
    await expect(editor).toHaveValue('尚未保存的新稿')
  } finally { await request.delete(`${api}/books/${book.id}`) }
})

test('正文保存和历史可用，移除分析入口，失败保存不会切走章节', async ({ page, request }, testInfo) => {
  const book = await (await request.post(`${api}/books`, { data: { title: '正文验收' } })).json()
  const other = await (await request.post(`${api}/books`, { data: { title: '另一本正文' } })).json()
  try {
    const chapter = await (await request.post(`${api}/books/${book.id}/chapters`, { data: { title: '开端', content: '原始正文。' } })).json()
    await request.post(`${api}/books/${book.id}/chapters`, { data: { title: '第二章', content: '另一章内容。' } })
    await request.post(`${api}/books/${other.id}/chapters`, { data: { title: '另一部小说', content: '独立的正文。' } })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`/books/${book.id}/reader`)
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    const editor = page.getByRole('textbox', { name: '章节正文' })
    await editor.fill('正文修改，保存后仍是纯文本。')
    await page.getByRole('button', { name: '保存新版本', exact: true }).click()
    await expect(page.getByText('有未保存修改')).toHaveCount(0)
    await expect(page.getByRole('button', { name: '分析本章角色' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '组合提示词' })).toHaveCount(0)
    await expect(page.getByText('本章梗概', { exact: true })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath('body.png'), fullPage: true })
    await page.getByRole('button', { name: '大纲', exact: true }).click()
    await page.getByRole('button', { name: '正文', exact: true }).click()
    await expect(editor).toHaveValue('正文修改，保存后仍是纯文本。')
    await editor.fill('保存失败也不能丢失的草稿')
    await page.route(`**/chapters/${chapter.id}/versions`, route => route.request().method() === 'POST'
      ? route.fulfill({ status: 500, body: '模拟保存失败' }) : route.continue())
    await page.locator('aside[aria-label="章节列表"]').getByRole('button', { name: /第二章/ }).click()
    await page.getByRole('button', { name: '保存并切换', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(editor).toHaveValue('保存失败也不能丢失的草稿')
    await page.getByRole('button', { name: '放弃修改并切换', exact: true }).click()
    await expect(editor).toHaveValue('另一章内容。')
    await page.goto(`/books/${other.id}/reader`)
    await expect(editor).toHaveValue('独立的正文。')
    await page.goto(`/books/${book.id}/graphify`)
    await expect(page).toHaveURL(new RegExp(`/books/${book.id}/reader$`))
  } finally {
    await request.delete(`${api}/books/${book.id}`)
    await request.delete(`${api}/books/${other.id}`)
  }
})
